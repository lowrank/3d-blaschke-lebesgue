#!/usr/bin/env python3
"""Generate all 584 projective-box proofs from untrusted integer proposals.

Every parameter value and every quadrature row is recomputed with
`decide +kernel`. This generator also checks the exact rational acceptance
margin and the agreement with the already proved parameter cover.
"""

import argparse
import hashlib
import json
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/projective_proposals.json"
CHOICES = ROOT / "data/projective_grids.txt"
REPORT = ROOT.parent / "verification/reports/run_52_192/projective_leaves.txt"
BASE = ROOT / "BlaschkeLebesgue/Certificates/Generated"
PREFIX = "BlaschkeLebesgue.Certificates.Generated"
SCALE = 2**52
SHARDS = 64


def interval(values):
    return "⟨" + ", ".join(map(str, values)) + "⟩"


def jet(values):
    return "⟨" + ", ".join(interval(values[i:i+2]) for i in (0, 2, 4)) + "⟩"


def rat(value):
    value = Q(value)
    return str(value.numerator) if value.denominator == 1 else f"{value.numerator} / {value.denominator}"


def namespace(index):
    return f"ProjectiveSuite.Box{index:03d}"


def header(imports, index, digest):
    return "module\n\n" + "\n".join(f"public import {x}" for x in imports) + f"""

/-!
Generated by `scripts/generate_projective_suite.py`; box {index}.
Proposal record SHA256: {digest}
All numerical premises below are independently proved by Lean's kernel.
-/

@[expose] public section

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async false

namespace BlaschkeLebesgue.Certificates.{namespace(index)}

open FixedPoint ProjectiveExpressions

"""


def footer(index):
    return f"\nend BlaschkeLebesgue.Certificates.{namespace(index)}\n"


def coordinates(data):
    i, j, da, db = data["box"]
    na, nb = 25 * 2**da, 25 * 2**db
    return i, j, na, nb


def results(data):
    return [sum(data["point_rows"])] + [sum(row[k] for row in data["gradient_rows"]) for k in range(4)]


def margin(data):
    i, j, na, nb = coordinates(data)
    v, al, ah, bl, bh = [Q(x, SCALE) for x in results(data)]
    c0, ca, cb = Q(153, 100000), Q(-601, 100000), Q(317, 20000)
    return v - (c0 + ca*Q(2*i+1,na) + cb*Q(2*j+1,nb)) - (
        Q(1,na)*max(abs(al-ca),abs(ah-ca)) + Q(1,nb)*max(abs(bl-cb),abs(bh-cb)))


def candidate_term(data):
    i, j, na, nb = coordinates(data)
    box = "⟨" + ", ".join(rat(x) for x in [Q(2*i,na),Q(2*i+2,na),Q(2*j,nb),Q(2*j+2,nb)]) + "⟩"
    values = ", ".join(rat(Q(x,SCALE)) for x in results(data))
    return f"⟨{box}, {rat(margin(data)/2)}, {values}⟩"


def validate(data):
    if data["precision"] != 52 or len(data["boxes"]) != 584:
        raise ValueError("Expected 584 boxes at precision 52")
    expected = [list(map(int, line.split()[:4])) for line in REPORT.read_text().splitlines()]
    choices = [list(map(int, line.split())) for line in CHOICES.read_text().splitlines()]
    if [box["box"] for box in data["boxes"]] != expected:
        raise ValueError("Proposals do not match the proved parameter cover in order")
    for box, choice in zip(data["boxes"], choices, strict=True):
        np, ng = box["point_grid"], box["gradient_grid"]
        if box["box"] + [np, ng] != choice:
            raise ValueError("Proposal grids differ from the grid-choice file")
        if not (0 < np <= 192 and 0 < ng <= 192):
            raise ValueError("Unsupported grid size")
        if len(box["parameters"]) != 4 or len(box["parameter_jets"]) != 8:
            raise ValueError("Invalid parameter proposal count")
        if len(box["point_rows"]) != np or len(box["gradient_rows"]) != ng:
            raise ValueError("Invalid row count")
        for row in box["parameters"] + box["parameter_jets"] + box["gradient_rows"]:
            if len(row) not in (2,4,6) or any(not isinstance(x,int) for x in row):
                raise ValueError("Invalid proposed interval record")
            if any(row[k] > row[k+1] for k in range(0,len(row),2)):
                raise ValueError("Empty proposed interval")
        if margin(box) <= 0:
            raise ValueError("Nonpositive rational acceptance margin")


def kernel(index, data, digest):
    np, ng = data["point_grid"], data["gradient_grid"]
    i, j, na, nb = coordinates(data)
    text = header(["BlaschkeLebesgue.Certificates.CenteredComputation"], index, digest)
    text += f"""def aCenter : Interval := Interval.rational 52 {2*i+1} {na}
def bCenter : Interval := Interval.rational 52 {2*j+1} {nb}
def aBox : Interval := Interval.span (Interval.rational 52 {2*i} {na}) (Interval.rational 52 {2*i+2} {na})
def bBox : Interval := Interval.span (Interval.rational 52 {2*j} {nb}) (Interval.rational 52 {2*j+2} {nb})

def parameters : Params Interval := ⟨{', '.join(map(interval,data['parameters']))}⟩
def pointRows : List ℤ := [{', '.join(map(str,data['point_rows']))}]

theorem parameters_verified : paramsInterval 52 aCenter bCenter = some parameters := by
  decide +kernel

"""
    for row, value in enumerate(data["point_rows"]):
        text += f"""theorem point_row_{row:02d} : ProjectivePointIntegral.sumRange {np}
    (fun j ↦ CenteredProjective.cell 52 {np} parameters {row} j) = some {value} := by
  decide +kernel

"""
    for axis, direction, offset in [("a","true",0),("b","false",1)]:
        jets = data["parameter_jets"][4*offset:4*offset+4]
        rows = [row[2*offset:2*offset+2] for row in data["gradient_rows"]]
        text += f"""def parameters_{axis} : Params Jet := ⟨{', '.join(map(jet,jets))}⟩
def rows_{axis} : List Interval := [{', '.join(map(interval,rows))}]

theorem parameters_{axis}_verified : parameterJets 52 {direction} aBox bBox = some parameters_{axis} := by
  decide +kernel

"""
        for row, value in enumerate(rows):
            text += f"""theorem {axis}_row_{row:02d} : ProjectiveGradientIntegral.sumRange {ng}
    (fun j ↦ ProjectiveGradientIntegral.cell 52 {ng} parameters_{axis} {row} j) = some {interval(value)} := by
  decide +kernel

"""
    return text + footer(index)


def assemble_rows(name, n, computation, par, row_list, prefix, result, param_proof, args):
    point = computation == "CenteredProjective"
    summation = "ProjectivePointIntegral" if point else computation
    return f"""theorem {name} : {computation}.check 52 {n} {args} = some {result} := by
  have hrows : ∀ i < {n}, {summation}.sumRange {n}
      (fun j ↦ {computation}.cell 52 {n} {par} i j) = {row_list}[i]? := by
    intro i hi
    interval_cases i
""" + "".join(f"    · exact {prefix}_{i:02d}\n" for i in range(n)) + f"""  have hsum : {summation}.sumRange {n} (fun i ↦ {row_list}[i]?) = some {result} := by
    decide +kernel
  have hgrid : {computation}.grid 52 {n} {par} = some {result} :=
    ({summation}.sumRange_congr hrows).trans hsum
  exact Option.bind_eq_some_iff.2 ⟨{par}, {param_proof}, hgrid⟩

"""


def assembly(index, data, digest):
    imports = ["BlaschkeLebesgue.Certificates.CenteredAnalyticBounds",
               f"{PREFIX}.ProjectiveKernel.Box{index:03d}"]
    text = header(imports, index, digest)
    np, ng = data["point_grid"], data["gradient_grid"]
    v, al, ah, bl, bh = results(data)
    text += assemble_rows("point_verified",np,"CenteredProjective","parameters","pointRows",
                          "point_row",str(v),"parameters_verified","aCenter bCenter")
    for axis, direction, vals in [("a","true",[al,ah]),("b","false",[bl,bh])]:
        text += assemble_rows(f"{axis}_verified",ng,"ProjectiveGradientIntegral",f"parameters_{axis}",
                              f"rows_{axis}",f"{axis}_row",f"({interval(vals)} : Interval)",
                              f"parameters_{axis}_verified",f"{direction} aBox bBox")
    text += f"""def candidate : ProjectiveAcceptance.Candidate :=
  {candidate_term(data)}

def entry : CenteredAnalyticBounds.Entry :=
  ⟨candidate, 52, {np}, {ng}, ⟨{v}, {interval([al,ah])}, {interval([bl,bh])}⟩⟩

theorem arithmetic_verified : candidate.check = true := by decide +kernel

theorem computations_verified : CenteredAnalyticBounds.check 52 {np} {ng} candidate entry.results = true := by
  have hma : ProjectiveAnalyticBounds.rational 52 candidate.box.aMid = aCenter := by decide +kernel
  have hmb : ProjectiveAnalyticBounds.rational 52 candidate.box.bMid = bCenter := by decide +kernel
  have hba : ProjectiveAnalyticBounds.boxA 52 candidate.box = aBox := by decide +kernel
  have hbb : ProjectiveAnalyticBounds.boxB 52 candidate.box = bBox := by decide +kernel
  apply CenteredAnalyticBounds.check_of_computations
  · decide +kernel
  · decide
  · decide +kernel
  · exact (congrArg₂ (CenteredProjective.check 52 {np}) hma hmb).trans point_verified
  · exact (congrArg₂ (ProjectiveGradientIntegral.check 52 {ng} true) hba hbb).trans a_verified
  · exact (congrArg₂ (ProjectiveGradientIntegral.check 52 {ng} false) hba hbb).trans b_verified

theorem entry_verified : entry.check = true :=
  CenteredAnalyticBounds.Entry.check_of_checks arithmetic_verified computations_verified
"""
    return text + footer(index)


def proposal_checks(boxes):
    candidates = ",\n   ".join(candidate_term(box) for box in boxes)
    return f"""module

public import BlaschkeLebesgue.Certificates.Generated.ProjectiveAcceptance

/-!
Generated by `scripts/generate_projective_suite.py`.
This checks the new candidates' cover and final rational arithmetic only.
Their center and gradient bounds are verified separately by the kernel suite.
-/

@[expose] public section

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace BlaschkeLebesgue.Certificates.ProjectiveProposals

def candidates : List ProjectiveAcceptance.Candidate :=
  [{candidates}]

theorem boxes_verified : candidates.map (·.box) = ParameterCover.Generated.boxes := by
  decide +kernel

theorem arithmetic_verified : candidates.all ProjectiveAcceptance.Candidate.check = true := by
  decide +kernel

end BlaschkeLebesgue.Certificates.ProjectiveProposals
"""


def aggregate(count):
    names = [f"Box{i:03d}" for i in range(count)]
    # Explicit proof composition avoids reducing any closed quadrature checker.
    proof = "rfl"
    for name in reversed(names):
        proof = f"all_cons_verified {name}.entry_verified ({proof})"
    imports = "\n".join(f"public import {PREFIX}.ProjectiveBoxes.Box{i:03d}" for i in range(count))
    return f"""module

{imports}

/-! Generated by `scripts/generate_projective_suite.py`. -/

@[expose] public section

set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace BlaschkeLebesgue.Certificates.ProjectiveSuite

def entries : List CenteredAnalyticBounds.Entry :=
  [{', '.join(name+'.entry' for name in names)}]

theorem boxes_verified : entries.map (fun e ↦ e.candidate.box) = ParameterCover.Generated.boxes := by
  decide +kernel

theorem all_cons_verified {{entry : CenteredAnalyticBounds.Entry}} {{entries : List CenteredAnalyticBounds.Entry}}
    (h : entry.check = true) (hs : entries.all CenteredAnalyticBounds.Entry.check = true) :
    (entry :: entries).all CenteredAnalyticBounds.Entry.check = true := by
  simp only [List.all_cons, h, hs, Bool.and_self]

theorem all_verified : entries.all CenteredAnalyticBounds.Entry.check = true :=
  {proof}

theorem completion_affine_lower {{a b : ℝ}} (ha : 0 ≤ a) (hb : 0 ≤ b) (hab : a + b ≤ 2 / 25) :
    (153 / 100000 : ℝ) - 601 / 100000 * a + 317 / 20000 * b < Completion.F a b :=
  CenteredAnalyticBounds.completion_affine_lower_of_entries boxes_verified all_verified ha hb hab

end BlaschkeLebesgue.Certificates.ProjectiveSuite
"""


def shard_plan(boxes):
    shards = [{"id": f"{i:02d}", "boxes": [], "weight": 0} for i in range(SHARDS)]
    for i in sorted(range(len(boxes)), key=lambda i: -(3*boxes[i]["point_grid"]**2+boxes[i]["gradient_grid"]**2)):
        shard = min(shards, key=lambda s: (s["weight"],s["id"]))
        shard["boxes"].append(i)
        shard["weight"] += 3*boxes[i]["point_grid"]**2+boxes[i]["gradient_grid"]**2
    for shard in shards:
        shard["boxes"].sort()
    return shards


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_bytes())
    validate(data)
    files = {}
    for index, box in enumerate(data["boxes"]):
        digest = hashlib.sha256(json.dumps(box,sort_keys=True).encode()).hexdigest()
        files[BASE / f"ProjectiveKernel/Box{index:03d}.lean"] = kernel(index,box,digest)
        files[BASE / f"ProjectiveBoxes/Box{index:03d}.lean"] = assembly(index,box,digest)
    files[BASE / "ProjectiveSuite.lean"] = aggregate(len(data["boxes"]))
    files[BASE / "ProjectiveProposalChecks.lean"] = proposal_checks(data["boxes"])
    files[ROOT / "data/projective_shards.json"] = json.dumps(shard_plan(data["boxes"]),indent=2)+"\n"
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Generated projective certificate differs: {path}")
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text)
    print(f"{'Checked' if args.check else 'Generated'} {len(data['boxes'])} boxes, "
          f"{sum(b['point_grid']+2*b['gradient_grid'] for b in data['boxes'])} row proofs, and {SHARDS} CI shards")


if __name__ == "__main__":
    main()
