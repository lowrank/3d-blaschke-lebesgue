#!/usr/bin/env python3
"""Emit literal candidate data; Lean recomputes and proves every acceptance test."""

import argparse
import hashlib
import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "verification/data/radial_candidates.json"
DESTINATION = ROOT / "BlaschkeLebesgue/Certificates/Generated"


def rational(value):
    q = Fraction(value)
    return f"({q.numerator} / {q.denominator})"


def literal_list(name, values):
    lines = [f"def {name} : List ℕ := ["]
    for start in range(0, len(values), 6):
        chunk = values[start:start + 6]
        suffix = "," if start + 6 < len(values) else "]"
        lines.append("  " + ", ".join(map(str, chunk)) + suffix)
    return "\n".join(lines)


def render(index, row, digest):
    if row["N"] != 4096 or row["denominator"] != 10**12:
        raise ValueError("The Lean checker expects the manuscript's fixed grid and scale")
    # Serialize expensive kernel checks to keep a cold CI build within memory limits.
    dependency = ("BlaschkeLebesgue.Certificates.RadialArithmetic" if index == 0 else
                  f"BlaschkeLebesgue.Certificates.Generated.Row{index - 1}")
    return f"""module

public import {dependency}

/-!
Generated by `scripts/generate_radial.py` from the original candidate integers.
Input SHA256: {digest}
No Python calculation is trusted by the theorem below: Lean checks `checkRow`.
-/

@[expose] public section

set_option maxRecDepth 20000
set_option maxHeartbeats 20000000

namespace BlaschkeLebesgue.Certificates.RadialArithmetic.Row{index}

def parameters : Parameters where
  lo := {rational(row['lo'])}
  hi := {rational(row['hi'])}
  tangentPoint := {rational(row['s0'])}
  expectedCoefficient := {rational(row['coefficient'])}

{literal_list('positive', row['w'])}

{literal_list('negative', row['z'])}

/-- All rational tests and the recomputed lower coefficient for this complete row. -/
theorem verified : checkRow parameters positive negative = true := by
  decide +kernel

end BlaschkeLebesgue.Certificates.RadialArithmetic.Row{index}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    rows = json.loads(raw)
    if len(rows) != 8:
        raise ValueError("Expected the eight manuscript rows")
    if not args.check:
        DESTINATION.mkdir(parents=True, exist_ok=True)
    for index, row in enumerate(rows):
        path = DESTINATION / f"Row{index}.lean"
        text = render(index, row, digest)
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Generated data differs: {path}")
        else:
            path.write_text(text)
    print(f"{'Checked' if args.check else 'Generated'} {len(rows)} radial rows; source {digest}")


if __name__ == "__main__":
    main()
