#!/usr/bin/env python3
"""Serialize the projective boxes, bisection cover, and acceptance candidates.

Lean checks every leaf lookup, rational bisection, and outside-triangle test.
Lean also checks the final acceptance arithmetic, conditional on the analytic
value/derivative bounds. This script does not establish those bounds.
"""

import argparse
import hashlib
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "verification/reports/run_52_192/projective_leaves.txt"
DESTINATION = ROOT / "BlaschkeLebesgue/Certificates/Generated/ProjectiveCover.lean"
ACCEPTANCE = ROOT / "BlaschkeLebesgue/Certificates/Generated/ProjectiveAcceptance.lean"


def rational(value):
    return f"({value.numerator} / {value.denominator})"


def box_literal(i, j, da, db):
    bounds = [Fraction(2 * i, 25 * 2**da), Fraction(2 * (i + 1), 25 * 2**da),
              Fraction(2 * j, 25 * 2**db), Fraction(2 * (j + 1), 25 * 2**db)]
    return "⟨" + ", ".join(map(rational, bounds)) + "⟩"


def render(raw):
    rows = [tuple(map(int, line.split()[:4])) for line in raw.decode().splitlines()]
    if len(rows) != 584 or len(set(rows)) != len(rows):
        raise ValueError("Expected 584 distinct accepted parameter boxes")
    lookup = {row: index for index, row in enumerate(rows)}
    lines = []
    for i, j, da, db in rows:
        lines.append("  " + box_literal(i, j, da, db))

    def tree(i, j, da, db):
        key = (i, j, da, db)
        if key in lookup:
            return f"(.accepted {lookup[key]})"
        if Fraction(i, 2**da) + Fraction(j, 2**db) > 1:
            return ".outside"
        if max(da, db) > 6:
            raise ValueError(f"Uncovered parameter box {key}")
        if da <= db:
            return f"(.splitA {tree(2*i, j, da+1, db)} {tree(2*i+1, j, da+1, db)})"
        return f"(.splitB {tree(i, 2*j, da, db+1)} {tree(i, 2*j+1, da, db+1)})"

    cover = tree(0, 0, 0, 0)
    boxes = ",\n".join(lines)
    # Line breaks keep the generated candidate readable without changing syntax.
    cover = cover.replace("(.splitA", "\n  (.splitA")
    return f"""module

public import BlaschkeLebesgue.Certificates.ParameterCover

/-!
Generated by `scripts/generate_projective_cover.py`.
Input: `verification/reports/run_52_192/projective_leaves.txt`.
Input SHA256: {hashlib.sha256(raw).hexdigest()}
Only the parameter cover and domain bounds are certified here.
The numerical integral and derivative columns are not proof inputs.
-/

@[expose] public section

set_option maxRecDepth 20000
set_option maxHeartbeats 20000000

namespace BlaschkeLebesgue.Certificates.ParameterCover.Generated

def boxes : List Box := [
{boxes}]

def tree : Tree := {cover}

theorem cover_verified : check boxes root tree = true := by
  decide +kernel

theorem domain_verified : boxes.all Box.domainCheck = true := by
  decide +kernel

theorem covers {{a b : ℝ}} (ha : 0 ≤ a) (hb : 0 ≤ b) (hab : a + b ≤ 2 / 25) :
    ∃ c ∈ boxes, c.Contains a b := covers_triangle cover_verified ha hb hab

theorem domain {{c : Box}} (hc : c ∈ boxes) {{a b : ℝ}} (hp : c.Contains a b) :
    0 ≤ a ∧ 0 ≤ b ∧ a + b ≤ 17 / 200 :=
  Box.domainCheck_sound ((List.all_eq_true.1 domain_verified) c hc) hp

end BlaschkeLebesgue.Certificates.ParameterCover.Generated
"""


def render_acceptance(raw):
    rows = [tuple(map(int, line.split())) for line in raw.decode().splitlines()]
    if len(rows) != 584 or any(len(row) != 10 for row in rows):
        raise ValueError("Expected 584 complete projective report rows")
    lines = []
    for i, j, da, db, margin, value, al, ah, bl, bh in rows:
        values = ", ".join(rational(Fraction(x, 2**52)) for x in (margin, value, al, ah, bl, bh))
        lines.append(f"  ⟨{box_literal(i, j, da, db)}, {values}⟩")
    candidates = ",\n".join(lines)
    return f"""module

public import BlaschkeLebesgue.Certificates.ProjectiveAcceptance
public import BlaschkeLebesgue.Certificates.Generated.ProjectiveCover

/-!
Generated by `scripts/generate_projective_cover.py`.
Input SHA256: {hashlib.sha256(raw).hexdigest()}
The final rational acceptance arithmetic is checked by the kernel.
The center-integral and signed secant enclosures remain explicit hypotheses.
-/

@[expose] public section

set_option maxRecDepth 20000
set_option maxHeartbeats 20000000

namespace BlaschkeLebesgue.Certificates.ProjectiveAcceptance.Generated

def candidates : List Candidate := [
{candidates}]

theorem arithmetic_verified : candidates.all Candidate.check = true := by
  decide +kernel

theorem boxes_match : candidates.map Candidate.box = ParameterCover.Generated.boxes := by
  decide +kernel

/-- This conditional assembly theorem does not establish its analytic premise.
That premise must be constructed by the interval/jet and quadrature proofs. -/
theorem completion_affine_lower_of_analytic_bounds
    (hBounds : ∀ c ∈ candidates, c.AnalyticBounds Completion.fixedSquareIntegral)
    {{a b : ℝ}} (ha : 0 ≤ a) (hb : 0 ≤ b) (hab : a + b ≤ 2 / 25) :
    (153 / 100000 : ℝ) - 601 / 100000 * a + 317 / 20000 * b < Completion.F a b := by
  obtain ⟨q, hq, hp⟩ := ParameterCover.Generated.covers ha hb hab
  rw [← boxes_match] at hq
  obtain ⟨c, hc, heq⟩ := List.mem_map.1 hq
  rw [← heq] at hp
  have h := Candidate.check_sound ((List.all_eq_true.1 arithmetic_verified) c hc) (hBounds c hc) hp
  rw [← Completion.F_eq_fixedSquareIntegral ha hb hab] at h
  exact h

end BlaschkeLebesgue.Certificates.ProjectiveAcceptance.Generated
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    for path, rendered in [(DESTINATION, render(raw)), (ACCEPTANCE, render_acceptance(raw))]:
        if args.check:
            if not path.exists() or path.read_text() != rendered:
                raise SystemExit(f"Generated projective data differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered)
    print(f"{'Checked' if args.check else 'Generated'} 584 parameter boxes, cover, and acceptance candidates")


if __name__ == "__main__":
    main()
