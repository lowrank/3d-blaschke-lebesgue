#!/usr/bin/env python3
"""Emit kernel proofs for the first report center on a centered 48-by-48 grid.

The JSON contains proposed integer outputs. Each row theorem recomputes its
full expression, derivative, retention, and quadrature checks in Lean's kernel.
The generator and the proposed integers are not trusted mathematical premises.
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/centered_first.json"
DESTINATION = ROOT / "BlaschkeLebesgue/Certificates/Generated/CenteredFirstKernel.lean"


def render(raw):
    data = json.loads(raw)
    if (data["precision"], data["grid"], data["a_num"], data["b_num"], data["denominator"]) != (52, 48, 1, 1, 1600):
        raise ValueError("Expected the first report center and the 52-bit, 48-by-48 grid")
    if len(data["row_sums"]) != 48 or len(data["parameters"]) != 4:
        raise ValueError("Expected four parameter intervals and 48 proposed row sums")
    parameters = ", ".join(f"⟨{lo}, {hi}⟩" for lo, hi in data["parameters"])
    values = ", ".join(map(str, data["row_sums"]))
    proofs = []
    for i, value in enumerate(data["row_sums"]):
        proofs.append(f"""theorem row_{i:02d} :
    ProjectivePointIntegral.sumRange 48 (fun j ↦ cell 52 48 parameters {i} j) = some {value} := by
  decide +kernel
""")
    proof_text = "\n".join(proofs)
    return f"""module

public import BlaschkeLebesgue.Certificates.CenteredComputation

/-!
Generated by `scripts/generate_centered_first.py`.
Proposed integer data SHA256: {hashlib.sha256(raw).hexdigest()}
Every row is independently recomputed by the kernel; no native-evaluation axiom.
-/

@[expose] public section

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async false

namespace BlaschkeLebesgue.Certificates.CenteredProjective.First

open FixedPoint ProjectiveExpressions

def parameters : Params Interval := ⟨{parameters}⟩

def rowValues : List ℤ := [{values}]

theorem parameters_verified :
    paramsInterval 52 (Interval.rational 52 1 1600) (Interval.rational 52 1 1600) = some parameters := by
  decide +kernel

{proof_text}
end BlaschkeLebesgue.Certificates.CenteredProjective.First
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render(SOURCE.read_bytes())
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != rendered:
            raise SystemExit(f"Generated centered check differs: {DESTINATION}")
        print("Checked 48 proposed row sums and their kernel theorem statements")
    else:
        DESTINATION.parent.mkdir(parents=True, exist_ok=True)
        DESTINATION.write_text(rendered)


if __name__ == "__main__":
    main()
