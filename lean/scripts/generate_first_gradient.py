#!/usr/bin/env python3
"""Emit independent kernel checks of the first box's two gradient grids.

All stored parameter jets and row intervals are proposals. Lean recomputes
every one using exact interval arithmetic and its checked expression program.
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/first_gradient.json"
DESTINATION = ROOT / "BlaschkeLebesgue/Certificates/Generated/FirstGradientKernel.lean"


def interval(lo, hi):
    return f"⟨{lo}, {hi}⟩"


def jet(row):
    return "⟨" + ", ".join(interval(*row[i:i+2]) for i in (0, 2, 4)) + "⟩"


def render(raw):
    data = json.loads(raw)
    if (data["precision"], data["grid"], data["box"]) != (52, 64, [0, 1, 0, 1, 800]):
        raise ValueError("Expected the first parameter box and the 52-bit, 64-by-64 gradient grid")
    if len(data["parameters"]) != 8 or len(data["rows"]) != 64:
        raise ValueError("Expected eight parameter jets and 64 pairs of row intervals")
    declarations = []
    for axis, direction, offset in [("a", "true", 0), ("b", "false", 1)]:
        parameters = ", ".join(jet(row) for row in data["parameters"][4*offset:4*offset+4])
        rows = [interval(*row[2*offset:2*offset+2]) for row in data["rows"]]
        declarations.append(f"""def parameters_{axis} : Params Jet := ⟨{parameters}⟩

def rows_{axis} : List Interval := [{", ".join(rows)}]

theorem parameters_{axis}_verified : parameterJets 52 {direction} box box = some parameters_{axis} := by
  decide +kernel
""")
        for i, row in enumerate(rows):
            declarations.append(f"""theorem row_{axis}_{i:02d} :
    sumRange 64 (fun j ↦ cell 52 64 parameters_{axis} {i} j) = some {row} := by
  decide +kernel
""")
    body = "\n".join(declarations)
    return f"""module

public import BlaschkeLebesgue.Certificates.ProjectiveComputation

/-!
Generated by `scripts/generate_first_gradient.py`.
Proposed integer data SHA256: {hashlib.sha256(raw).hexdigest()}
The two parameter jets and all 128 row intervals are recomputed by the kernel.
-/

@[expose] public section

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async false

namespace BlaschkeLebesgue.Certificates.ProjectiveGradientIntegral.First

open FixedPoint ProjectiveExpressions

def box : Interval := Interval.span (Interval.rational 52 0 1) (Interval.rational 52 1 800)

{body}
end BlaschkeLebesgue.Certificates.ProjectiveGradientIntegral.First
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render(SOURCE.read_bytes())
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != rendered:
            raise SystemExit(f"Generated gradient check differs: {DESTINATION}")
        print("Checked 128 proposed gradient row intervals and their kernel theorem statements")
    else:
        DESTINATION.parent.mkdir(parents=True, exist_ok=True)
        DESTINATION.write_text(rendered)


if __name__ == "__main__":
    main()
